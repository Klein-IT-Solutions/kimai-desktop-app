#!/usr/bin/env bash
# Generates THIRD_PARTY_NOTICES.md (and the installer copy of LICENSE): the licenses of all third-party code that
# is compiled into or shipped with Kimai Tracker. Run after `make deps`
# (needs the Go module cache, frontend/node_modules and third_party/whisper.cpp):
#
#   make notices
#
# Add new dependencies here when they end up in the binary or the frontend bundle
# (check with `go version -m bin/kimai-tracker` and a Vite build with sourcemaps).
set -euo pipefail
cd "$(dirname "$0")/.."
out=THIRD_PARTY_NOTICES.md

moddir() { go list -m -f '{{.Dir}}' "$1"; }
npmdir() { echo "frontend/node_modules/$1"; }
modver() { go list -m -f '{{.Version}}' "$1"; }
npmver() { node -p "require('./frontend/node_modules/$1/package.json').version"; }

# name | version | license | license file | where it is used
entries=()
add() { entries+=("$1|$2|$3|$4|$5"); }

W=$(moddir github.com/wailsapp/wails/v3)
add "Go standard library" "$(go list -m -f 'go{{.GoVersion}}')" "BSD-3-Clause" "$(go env GOROOT)/LICENSE" "all platforms"
add "Wails" "$(modver github.com/wailsapp/wails/v3)" "MIT" "$W/LICENSE" "all platforms"
add "go-common-file-dialog (in Wails)" "–" "MIT" "$W/internal/go-common-file-dialog/LICENSE" "Windows"
add "go-webview2 loader (in Wails)" "–" "ISC" "$W/internal/webview2/webviewloader/LICENSE" "Windows"
for m in github.com/zalando/go-keyring github.com/godbus/dbus/v5 github.com/jezek/xgb github.com/gen2brain/malgo \
  golang.org/x/sys github.com/adrg/xdg github.com/danieljoos/wincred github.com/go-ole/go-ole git.sr.ht/~jackmordaunt/go-toast/v2; do
  d=$(moddir "$m")
  f=$(ls "$d" | grep -iE '^(licen[cs]e|copying|unlicense)' | head -1)
  case "$m" in
  github.com/godbus/dbus/v5 | github.com/jezek/xgb | golang.org/x/sys) lic="BSD" ;;
  github.com/gen2brain/malgo) lic="Unlicense (public domain); contains miniaudio (public domain or MIT-0)" ;;
  git.sr.ht/*) lic="MIT or Unlicense" ;;
  *) lic="MIT" ;;
  esac
  case "$m" in
  github.com/godbus/* | github.com/jezek/*) use="Linux" ;;
  github.com/danieljoos/* | github.com/go-ole/* | git.sr.ht/*) use="Windows" ;;
  *) use="all platforms" ;;
  esac
  add "$m" "$(modver "$m")" "$lic" "$d/$f" "$use"
done
add "whisper.cpp (incl. ggml)" "$(cd third_party/whisper.cpp && git describe --tags 2>/dev/null || echo '?')" "MIT" "third_party/whisper.cpp/LICENSE" "all platforms (speech recognition)"
npmlicense() { find "$(npmdir "$1")" -maxdepth 1 -iname 'licen[cs]e*' | head -1; }
for p in svelte clsx tailwindcss; do
  add "$p" "$(npmver "$p")" "MIT" "$(npmlicense "$p")" "user interface"
done
# The npm package carries no license file; it is part of the Wails project (MIT).
add "@wailsio/runtime" "$(npmver @wailsio/runtime)" "MIT" "$W/LICENSE" "user interface"
add "Inter typeface (@fontsource-variable/inter)" "$(npmver @fontsource-variable/inter)" "SIL Open Font License 1.1" "$(npmlicense @fontsource-variable/inter)" "user interface"

{
  cat <<'HEAD'
# Third-party notices

Kimai Tracker contains the following third-party software. Each component is
licensed under its own terms, reproduced below. These terms apply to the
respective component; the license of Kimai Tracker (`LICENSE`) does not restrict
the rights they grant.

<!-- Generated by scripts/third-party-notices.sh – do not edit by hand. -->

| Component | Version | License | Used |
| --------- | ------- | ------- | ---- |
HEAD
  for e in "${entries[@]}"; do
    IFS='|' read -r name ver lic file use <<<"$e"
    echo "| $name | $ver | $lic | $use |"
  done
  cat <<'MID'
| GCC runtime (libstdc++, libgcc) | – | GPL-3.0 with GCC Runtime Library Exception 3.1 | Windows (linked statically) |
| mingw-w64 winpthreads | – | MIT and BSD-3-Clause | Windows (linked statically) |
| Microsoft Edge WebView2 Evergreen Bootstrapper | – | Microsoft software license | Windows installer |

